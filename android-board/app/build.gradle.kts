import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
}

// Secret Google Calendar iCal addresses and display settings: they live only in
// the ignored local.properties.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun localProp(key: String): String = localProps.getProperty(key, "").trim()

// Colors the web UI knows (style.css .cal-color--*); calendars without
// CAL_n_COLOR take them in this order.
val calendarColors = listOf("red", "green", "blue", "amber", "purple", "teal")

data class CalendarConfig(val name: String, val url: String, val color: String)

// One calendar per person: CAL_1_NAME / CAL_1_URL / CAL_1_COLOR (optional), CAL_2_…
// A lone ICAL_URL (the original setup) still works as one unnamed calendar.
val calendars: List<CalendarConfig> = run {
    val numbered = (1..20).mapNotNull { n ->
        val url = localProp("CAL_${n}_URL")
        if (url.isEmpty()) return@mapNotNull null
        val color = localProp("CAL_${n}_COLOR").lowercase()
        require(color.isEmpty() || color in calendarColors) {
            "CAL_${n}_COLOR=$color in local.properties: use one of ${calendarColors.joinToString()}"
        }
        CalendarConfig(localProp("CAL_${n}_NAME"), url, color)
    }
    val all = numbered.ifEmpty {
        localProp("ICAL_URL").let { if (it.isEmpty()) emptyList() else listOf(CalendarConfig("", it, "")) }
    }
    all.mapIndexed { i, c -> c.copy(color = c.color.ifEmpty { calendarColors[i % calendarColors.size] }) }
}

// Which way the TV is turned: ccw (anticlockwise), cw (clockwise) or none.
val rotation: String = localProp("ROTATION").lowercase().ifEmpty { "ccw" }.also {
    require(it in listOf("ccw", "cw", "none")) { "ROTATION=$it in local.properties: use ccw, cw or none" }
}

val configAssetsDir = layout.buildDirectory.dir("generated/config-assets")

fun javaString(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

android {
    namespace = "com.pearboard.tv"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.pearboard.tv"
        minSdk = 25 // Fire OS 6
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"

        // Only the addresses go to Kotlin; names and colors go to the page through config.js.
        buildConfigField(
            "String[]", "CALENDAR_URLS",
            calendars.joinToString(", ", "new String[] {", "}") { javaString(it.url) },
        )
    }

    buildFeatures {
        buildConfig = true
    }

    sourceSets["main"].assets.srcDir(configAssetsDir)

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
}

// assets/web/config.js: what the page needs to know about the build (no secrets).
val webConfigJson: String = groovy.json.JsonOutput.toJson(
    mapOf(
        "rotation" to rotation,
        "calendars" to calendars.map { mapOf("name" to it.name, "color" to it.color) },
    ),
)
val writeWebConfig by tasks.registering {
    val out = configAssetsDir.map { it.file("web/config.js") }
    inputs.property("config", webConfigJson)
    outputs.file(out)
    doLast {
        out.get().asFile.writeText(
            "// Generated by app/build.gradle.kts from local.properties.\n" +
                "window.PEARBOARD = $webConfigJson;\n" +
                "document.documentElement.setAttribute(\"data-rotate\", window.PEARBOARD.rotation);\n",
        )
    }
}
tasks.named("preBuild") { dependsOn(writeWebConfig) }

dependencies {
    implementation("androidx.webkit:webkit:1.11.0")
}
